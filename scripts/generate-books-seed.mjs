#!/usr/bin/env node
/**
 * Generates supabase/seed/books.sql from the same INITIAL_BOOKS seed data
 * BooksContext already reads today — so the eventual Supabase-backed books
 * table starts from the exact real catalog currently live on the site, not
 * a re-typed copy that could drift.
 *
 * This is the ONLY place a book's raw category name (e.g. "الأمومة
 * والإلهام الإسلامي") is ever resolved to a categories.id (e.g.
 * "cat-motherhood") — a plain, reviewable, static lookup table below, run
 * once, offline. No runtime application code performs this resolution;
 * BooksContext reads/writes category_id as an opaque column and continues
 * reading the display category name from content.category (see
 * booksRepository.ts's toSupabaseRow/fromSupabaseRow).
 *
 * This script only writes a SQL text file — it never connects to Supabase
 * and never executes anything against a database.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { INITIAL_BOOKS } from "../src/admin/data/booksData.ts";
import { toSupabaseRow } from "../src/admin/context/booksRepository.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_DIR = resolve(__dirname, "../supabase/seed");
const OUTPUT_PATH = resolve(OUTPUT_DIR, "books.sql");

// Reviewed by hand against the live categories table (Phase 5.5) rather
// than looked up at generation time — a static map is easier to review in
// a code diff than a network call's result. "قريبًا" is the coming-soon
// placeholder used by non-published books today; it was never a real
// category (see CategoriesContext's own COMING_SOON_CATEGORY_PLACEHOLDER),
// so it resolves to null, not a guess.
const CATEGORY_NAME_TO_ID = {
  "الأمومة والإلهام الإسلامي": "cat-motherhood",
  "التطوير الذاتي": "cat-self-development",
  "الروحانيات": "cat-spirituality",
  "الأدب والسيرة": "cat-literature",
  "تربية الأبناء": "cat-parenting",
  "قريبًا": null,
};

function resolveCategoryId(categoryName) {
  if (!(categoryName in CATEGORY_NAME_TO_ID)) {
    throw new Error(
      `generate-books-seed: no category mapping for "${categoryName}" — add it to CATEGORY_NAME_TO_ID above before regenerating.`
    );
  }
  return CATEGORY_NAME_TO_ID[categoryName];
}

function jsonbLiteral(value) {
  const json = JSON.stringify(value);
  return `'${json.replace(/'/g, "''")}'::jsonb`;
}

function textLiteral(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function nullableTextLiteral(value) {
  return value === null || value === undefined ? "null" : textLiteral(value);
}

function textArrayLiteral(values) {
  if (values.length === 0) return "'{}'";
  const escaped = values.map((v) => String(v).replace(/"/g, '\\"'));
  return `'{${escaped.map((v) => `"${v}"`).join(",")}}'`;
}

const rows = INITIAL_BOOKS.map((book) => {
  const categoryId = resolveCategoryId(book.category);
  const row = toSupabaseRow(book, categoryId);
  return `  (
    ${textLiteral(row.id)},
    ${textLiteral(row.author)},
    ${textLiteral(row.author_slug)},
    ${jsonbLiteral(row.author_bio)},
    ${nullableTextLiteral(row.category_id)},
    ${textLiteral(row.placement)},
    ${row.display_order},
    ${textLiteral(row.status)},
    ${jsonbLiteral(row.prices)},
    ${row.stock},
    ${textLiteral(row.sku)},
    ${row.pages},
    ${row.sales},
    ${nullableTextLiteral(row.accent_color)},
    ${nullableTextLiteral(row.cover)},
    ${nullableTextLiteral(row.back_cover_image)},
    ${textArrayLiteral(row.gallery)},
    ${textArrayLiteral(row.preview_pages)},
    ${jsonbLiteral(row.content)},
    ${nullableTextLiteral(row.deleted_at)}
  )`;
}).join(",\n");

const sql = `-- Generated by scripts/generate-books-seed.mjs from
-- src/admin/data/booksData.ts's INITIAL_BOOKS — do not hand-edit, re-run
-- the generator instead so this never drifts from the real seed.
--
-- NOT auto-applied by \`supabase db push\`/\`db reset\`. Run manually
-- (Supabase SQL Editor or \`psql -f\`) as a deliberate step in the Books
-- migration, only after the repository has been verified against this
-- data independently.
insert into public.books (
  id, author, author_slug, author_bio, category_id, placement,
  display_order, status, prices, stock, sku, pages, sales, accent_color,
  cover, back_cover_image, gallery, preview_pages, content, deleted_at
)
values
${rows}
on conflict (id) do nothing;
`;

mkdirSync(OUTPUT_DIR, { recursive: true });
writeFileSync(OUTPUT_PATH, sql, "utf-8");
console.log(`Books seed written to ${OUTPUT_PATH} (${INITIAL_BOOKS.length} rows). Not executed.`);
