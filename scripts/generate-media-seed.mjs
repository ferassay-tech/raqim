#!/usr/bin/env node
/**
 * Generates supabase/seed/media.sql from the same INITIAL_MEDIA_FOLDERS/
 * INITIAL_MEDIA_ASSETS seed data MediaContext already reads today — 3
 * real folders and 21 real assets, every one already pointing at a
 * currently-deployed /public file.
 *
 * No URL healing is needed here (unlike MediaContext.tsx's own
 * LEGACY_OFFICIAL_URLS reconciliation, which only matters for an already-
 * persisted browser's stale data) — INITIAL_MEDIA_ASSETS already holds
 * each asset's current, correct path.
 *
 * This script only writes a SQL text file — it never connects to Supabase
 * and never executes anything against a database.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { INITIAL_MEDIA_ASSETS, INITIAL_MEDIA_FOLDERS } from "../src/admin/data/mediaData.ts";
import { assetToSupabaseRow, folderToSupabaseRow } from "../src/admin/context/mediaRepository.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_DIR = resolve(__dirname, "../supabase/seed");
const OUTPUT_PATH = resolve(OUTPUT_DIR, "media.sql");

function textLiteral(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function nullableTextLiteral(value) {
  return value === null || value === undefined ? "null" : textLiteral(value);
}

function nullableNumberLiteral(value) {
  return value === null || value === undefined ? "null" : String(value);
}

const folderRows = INITIAL_MEDIA_FOLDERS.map(folderToSupabaseRow)
  .map((row) => `  (${textLiteral(row.id)}, ${textLiteral(row.name)})`)
  .join(",\n");

const assetRows = INITIAL_MEDIA_ASSETS.map(assetToSupabaseRow)
  .map(
    (row) =>
      `  (${textLiteral(row.id)}, ${textLiteral(row.storage_key)}, ${textLiteral(row.url)}, ${textLiteral(row.name)}, ${textLiteral(row.type)}, ${nullableTextLiteral(row.folder_id)}, ${row.size}, ${nullableNumberLiteral(row.width)}, ${nullableNumberLiteral(row.height)})`
  )
  .join(",\n");

const sql = `-- Generated by scripts/generate-media-seed.mjs from
-- src/admin/data/mediaData.ts's INITIAL_MEDIA_FOLDERS/INITIAL_MEDIA_ASSETS —
-- do not hand-edit, re-run the generator instead so this never drifts.
--
-- NOT auto-applied by \`supabase db push\`/\`db reset\`. Run manually
-- (Supabase SQL Editor or \`psql -f\`) as a deliberate step in the Media
-- migration, only after the repository has been verified independently.
-- Folders first -- media_assets.folder_id references media_folders.id.
insert into public.media_folders (id, name)
values
${folderRows}
on conflict (id) do nothing;

insert into public.media_assets (id, storage_key, url, name, type, folder_id, size, width, height)
values
${assetRows}
on conflict (id) do nothing;
`;

mkdirSync(OUTPUT_DIR, { recursive: true });
writeFileSync(OUTPUT_PATH, sql, "utf-8");
console.log(
  `Media seed written to ${OUTPUT_PATH} (${INITIAL_MEDIA_FOLDERS.length} folders, ${INITIAL_MEDIA_ASSETS.length} assets). Not executed.`
);
