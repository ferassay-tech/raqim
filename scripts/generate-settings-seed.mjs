#!/usr/bin/env node
/**
 * Generates supabase/seed/settings.sql from the same INITIAL_SETTINGS
 * SettingsContext already reads today - the site's real, live production
 * defaults (not placeholder data), as one jsonb document.
 *
 * This script only writes a SQL text file — it never connects to Supabase
 * and never executes anything against a database.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { INITIAL_SETTINGS } from "../src/admin/data/settingsData.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_DIR = resolve(__dirname, "../supabase/seed");
const OUTPUT_PATH = resolve(OUTPUT_DIR, "settings.sql");

const jsonLiteral = JSON.stringify(INITIAL_SETTINGS).replace(/'/g, "''");

const sql = `-- Generated by scripts/generate-settings-seed.mjs from
-- src/admin/data/settingsData.ts's INITIAL_SETTINGS — do not hand-edit,
-- re-run the generator instead so this never drifts.
--
-- NOT auto-applied by \`supabase db push\`/\`db reset\`. Run manually
-- (Supabase SQL Editor or \`psql -f\`) as a deliberate step in the
-- Settings migration, only after the repository has been verified
-- independently.
insert into public.site_settings (scope, data)
values ('default', '${jsonLiteral}'::jsonb)
on conflict (scope) do nothing;
`;

mkdirSync(OUTPUT_DIR, { recursive: true });
writeFileSync(OUTPUT_PATH, sql, "utf-8");
console.log(`Settings seed written to ${OUTPUT_PATH}. Not executed.`);
