#!/usr/bin/env node
/**
 * Generates supabase/seed/articles.sql from the same INITIAL_ARTICLES
 * ArticlesContext already reads today — 3 real, published blog posts.
 *
 * This script only writes a SQL text file — it never connects to Supabase
 * and never executes anything against a database.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { INITIAL_ARTICLES } from "../src/admin/data/articlesData.ts";
import { articleToSupabaseRow } from "../src/admin/context/articlesRepository.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_DIR = resolve(__dirname, "../supabase/seed");
const OUTPUT_PATH = resolve(OUTPUT_DIR, "articles.sql");

function textLiteral(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function nullableTextLiteral(value) {
  return value === null || value === undefined ? "null" : textLiteral(value);
}

function jsonbLiteral(value) {
  return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
}

const rows = INITIAL_ARTICLES.map(articleToSupabaseRow)
  .map(
    (row) =>
      `  (${textLiteral(row.id)}, ${jsonbLiteral(row.title)}, ${textLiteral(row.slug)}, ${jsonbLiteral(row.excerpt)}, ${jsonbLiteral(row.content)}, ${nullableTextLiteral(row.cover_image)}, ${textLiteral(row.author)}, ${jsonbLiteral(row.category)}, ${textLiteral(row.read_time)}, ${textLiteral(row.status)}, ${nullableTextLiteral(row.scheduled_for)}, ${nullableTextLiteral(row.published_at)}, ${jsonbLiteral(row.seo_title)}, ${jsonbLiteral(row.seo_description)})`
  )
  .join(",\n");

const sql = `-- Generated by scripts/generate-articles-seed.mjs from
-- src/admin/data/articlesData.ts's INITIAL_ARTICLES — do not hand-edit,
-- re-run the generator instead so this never drifts.
--
-- NOT auto-applied by \`supabase db push\`/\`db reset\`. Run manually
-- (Supabase SQL Editor or \`psql -f\`) as a deliberate step in the
-- Articles migration, only after the repository has been verified
-- independently.
insert into public.articles (id, title, slug, excerpt, content, cover_image, author, category, read_time, status, scheduled_for, published_at, seo_title, seo_description)
values
${rows}
on conflict (id) do nothing;
`;

mkdirSync(OUTPUT_DIR, { recursive: true });
writeFileSync(OUTPUT_PATH, sql, "utf-8");
console.log(`Articles seed written to ${OUTPUT_PATH} (${INITIAL_ARTICLES.length} posts). Not executed.`);
