#!/usr/bin/env node
/**
 * Generates supabase/seed/categories.sql from the same INITIAL_CATEGORIES
 * seed data CategoriesContext already reads today — so the eventual
 * Supabase-backed categories table starts from the exact real taxonomy
 * currently live on the site, not a re-typed copy that could drift.
 *
 * This script only writes a SQL text file — it never connects to Supabase
 * and never executes anything against a database. Applying the generated
 * file (e.g. via the Supabase SQL Editor, or `psql -f`) is a deliberate,
 * separate, manual step for a future migration phase.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { INITIAL_CATEGORIES } from "../src/admin/data/categoriesData.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_DIR = resolve(__dirname, "../supabase/seed");
const OUTPUT_PATH = resolve(OUTPUT_DIR, "categories.sql");

/** Escapes a JS value as a single-quoted Postgres text literal containing
 * JSON — doubles any embedded single quotes, the standard SQL-string
 * escaping rule. */
function jsonbLiteral(value) {
  const json = JSON.stringify(value);
  return `'${json.replace(/'/g, "''")}'::jsonb`;
}

function textLiteral(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

const rows = INITIAL_CATEGORIES.map(
  (c) => `  (${textLiteral(c.id)}, ${jsonbLiteral(c.name)}, ${jsonbLiteral(c.description)})`
).join(",\n");

const sql = `-- Generated by scripts/generate-categories-seed.mjs from
-- src/admin/data/categoriesData.ts's INITIAL_CATEGORIES — do not hand-edit,
-- re-run the generator instead so this never drifts from the real seed.
--
-- NOT auto-applied by \`supabase db push\`/\`db reset\`. Run manually
-- (Supabase SQL Editor or \`psql -f\`) as a deliberate step in the future
-- Categories migration phase — this file only exists to have that step
-- ready in advance.
insert into public.categories (id, name, description)
values
${rows}
on conflict (id) do nothing;
`;

mkdirSync(OUTPUT_DIR, { recursive: true });
writeFileSync(OUTPUT_PATH, sql, "utf-8");
console.log(`Categories seed written to ${OUTPUT_PATH} (${INITIAL_CATEGORIES.length} rows). Not executed.`);
