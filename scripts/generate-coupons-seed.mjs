#!/usr/bin/env node
/**
 * Generates supabase/seed/coupons.sql from the same INITIAL_COUPONS seed
 * data CouponsContext already reads today — 5 real starter codes, all
 * seeded disabled.
 *
 * This script only writes a SQL text file — it never connects to Supabase
 * and never executes anything against a database.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { INITIAL_COUPONS } from "../src/admin/data/couponsData.ts";
import { couponToSupabaseRow } from "../src/admin/context/couponsRepository.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_DIR = resolve(__dirname, "../supabase/seed");
const OUTPUT_PATH = resolve(OUTPUT_DIR, "coupons.sql");

function textLiteral(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function nullableTextLiteral(value) {
  return value === null || value === undefined ? "null" : textLiteral(value);
}

function nullableNumberLiteral(value) {
  return value === null || value === undefined ? "null" : String(value);
}

const rows = INITIAL_COUPONS.map(couponToSupabaseRow)
  .map(
    (row) =>
      `  (${textLiteral(row.id)}, ${textLiteral(row.code)}, ${textLiteral(row.type)}, ${row.value}, ${nullableNumberLiteral(row.min_order_value)}, ${nullableNumberLiteral(row.usage_limit)}, ${row.usage_count}, ${nullableTextLiteral(row.starts_at)}, ${nullableTextLiteral(row.expires_at)}, ${row.enabled}, ${textLiteral(row.description)})`
  )
  .join(",\n");

const sql = `-- Generated by scripts/generate-coupons-seed.mjs from
-- src/admin/data/couponsData.ts's INITIAL_COUPONS — do not hand-edit,
-- re-run the generator instead so this never drifts.
--
-- NOT auto-applied by \`supabase db push\`/\`db reset\`. Run manually
-- (Supabase SQL Editor or \`psql -f\`) as a deliberate step in the Coupons
-- migration, only after the repository has been verified independently.
insert into public.coupons (id, code, type, value, min_order_value, usage_limit, usage_count, starts_at, expires_at, enabled, description)
values
${rows}
on conflict (id) do nothing;
`;

mkdirSync(OUTPUT_DIR, { recursive: true });
writeFileSync(OUTPUT_PATH, sql, "utf-8");
console.log(`Coupons seed written to ${OUTPUT_PATH} (${INITIAL_COUPONS.length} codes). Not executed.`);
